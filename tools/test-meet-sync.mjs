import {test} from 'node:test';
import assert from 'node:assert/strict';
import {fixture} from './app-sync-fixture.mjs';
const today=()=>new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Berlin',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const later=n=>new Date(Date.parse(today()+'T12:00:00Z')+n*86400000).toISOString().slice(0,10);
const group=(f,id='group',extra={})=>({kind:'group',id,revision:0,value:{name:'Synthetic training group',createdBy:f.admin.id,members:[f.admin.id],pending:[f.otherId],weekday:3,time:'18:00',place:'Court',...extra}});
const meet=(f,id='meeting',extra={})=>({kind:'meet',id,revision:0,value:{kind:'einzel',title:'Tennis',createdBy:f.admin.id,invitees:[f.admin.id,f.otherId],date:later(2),time:'18:00',place:'Court',slots:2,...extra}});
const series=(f,extra={})=>({kind:'series',id:'series',revision:0,value:{...meet(f).value,groupId:'group',kind:'training',slots:null,from:later(1),until:later(22),leadDays:3,skipped:[],...extra}});
const answer=(f,target=f.otherId,extra={})=>({kind:'meet-answer',id:'meeting:'+target,revision:0,value:{meetId:'meeting',memberId:target,a:'yes',note:'',...extra}});
async function outsider(f){const id=crypto.randomUUID(),token='c'.repeat(64);f.env.DB.sqlite.prepare("INSERT INTO members(id,first_name,last_name,updated_at) VALUES (?,'Outside','Test',?)").run(id,Date.now());const h=Buffer.from(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(token))).toString('hex');f.env.DB.sqlite.prepare('INSERT INTO sessions VALUES (?,?,?)').run(h,id,Date.now()+100000);return {id,token};}

test('groups and training survive sessions; only invited members can read them or respond',async()=>{
 const f=await fixture(),out=await outsider(f);
 assert.equal((await f.commit([group(f)])).status,200);
 let state=(await f.state(f.otherToken)).body;
 assert.equal(state.meetings.groups[0].name,'Synthetic training group');assert.equal(state.meetings.inbox[0].type,'group-invite');
 assert.equal((await f.state(out.token)).body.meetings.groups.length,0);
 assert.equal((await f.commit([{kind:'group-answer',id:'group:'+out.id,revision:0,value:{groupId:'group',status:'yes'}}],out.token)).status,403);
 assert.equal((await f.commit([{kind:'group-answer',id:'group:'+f.otherId,revision:0,value:{groupId:'group',status:'yes'}}],f.otherToken)).status,200);
 state=(await f.state()).body;assert.ok(state.meetings.groups[0].members.includes(f.otherId));assert.equal(state.meetings.inbox[0].type,'group-yes');
 assert.equal((await f.commit([{...group(f),revision:1,value:{...group(f).value,name:'Hijacked'}}],f.otherToken)).status,403);
});

test('separate response records preserve simultaneous answers; creator may explicitly record a proxy answer',async()=>{
 const f=await fixture();await f.commit([meet(f)]);
 const replies=await Promise.all([f.commit([answer(f,f.admin.id)]),f.commit([answer(f)],f.otherToken)]);assert.deepEqual(replies.map(r=>r.status),[200,200]);
 let m=(await f.state()).body.meetings.meets[0];assert.equal(Object.keys(m.responses).length,2);
 const out=await outsider(f);
 assert.equal((await f.commit([answer(f,out.id)],out.token)).status,403);
 assert.equal((await f.commit([{...answer(f),revision:1,value:{...answer(f).value,a:'no'}}])).status,200);
 m=(await f.state(f.otherToken)).body.meetings.meets[0];assert.equal(m.responses[f.otherId].a,'no');assert.equal(m.responses[f.otherId].by,f.admin.id);
 assert.equal((await f.commit([{...answer(f),revision:1}],f.otherToken)).status,409);
});

test('weekly dates are generated by the server exactly once, with deterministic IDs across devices',async()=>{
 const f=await fixture();await f.commit([group(f),series(f)]);
 const a=(await f.state()).body,b=(await f.state(f.otherToken)).body;
 assert.equal(a.meetings.series.length,1);assert.equal(a.meetings.meets.length,1);assert.equal(b.meetings.meets[0].id,a.meetings.meets[0].id);
 assert.equal(f.env.DB.sqlite.prepare("SELECT COUNT(*) n FROM app_records WHERE kind='meet'").get().n,1);
 const id=a.meetings.meets[0].id;
 assert.equal((await f.commit([{kind:'meet',id,revision:1,deleted:true}])).status,200);
 assert.equal((await f.state()).body.meetings.meets.length,0);
 assert.equal((await f.state(f.otherToken)).body.meetings.inbox.some(n=>n.type==='cancel'),true);
});

test('migration preserves original groups, series, dates and answers, and reserves dates during interrupted imports',async()=>{
 const f=await fixture();
 assert.equal((await f.commit([group(f,'group',{members:[f.admin.id,f.otherId],pending:[]}),series(f,{reservedDates:[later(1)]})],f.adminToken,{importing:true})).status,200);
 assert.equal((await f.state()).body.meetings.meets.length,0);
 const at=Date.now()-3600000;
 assert.equal((await f.commit([meet(f,'meeting',{groupId:'group',seriesId:'series',kind:'training',slots:null,date:later(1)}),answer(f,f.admin.id,{at}),answer(f,f.otherId,{at:at+1000,note:'Original note'})],f.adminToken,{importing:true})).status,200);
 const state=(await f.state(f.otherToken)).body;
 assert.equal(state.meetings.meets.length,1);assert.equal(state.meetings.meets[0].id,'meeting');assert.equal(state.meetings.meets[0].responses[f.otherId].at,at+1000);assert.equal(state.meetings.meets[0].responses[f.otherId].note,'Original note');assert.equal(state.meetings.meets[0].responses[f.otherId].by,undefined);
 assert.ok(state.meetings.groups[0].members.includes(f.otherId));assert.equal((await f.commit([group(f)],f.adminToken,{importing:true})).status,409);
});

test('read/dismissed invitations are shared across devices; reminders are restricted to the creator',async()=>{
 const f=await fixture();await f.commit([meet(f)]);
 const n=(await f.state(f.otherToken)).body.meetings.inbox[0];
 await f.commit([{kind:'meet-inbox',id:f.otherId,revision:0,value:{read:[n.id],dismissed:[]}}],f.otherToken);
 assert.equal((await f.state(f.otherToken)).body.meetings.inbox[0].read,true);
 await f.commit([{kind:'meet-inbox',id:f.otherId,revision:0,value:{read:[],dismissed:[n.id]}}],f.otherToken);
 assert.equal((await f.state(f.otherToken)).body.meetings.inbox.length,0);
 const reminder={kind:'meet-remind',id:'reminder-test',revision:0,value:{meetId:'meeting'}};
 assert.equal((await f.commit([reminder],f.otherToken)).status,403);
 assert.equal((await f.commit([reminder])).status,200);
 assert.equal((await f.state(f.otherToken)).body.meetings.inbox[0].type,'remind');
});

test('declining a group stops access and anonymous or deactivated sessions cannot access plans',async()=>{
 const f=await fixture();await f.commit([group(f)]);
 await f.commit([{kind:'group-answer',id:'group:'+f.otherId,revision:0,value:{groupId:'group',status:'no'}}],f.otherToken);
 assert.equal((await f.state(f.otherToken)).body.meetings.groups.length,0);
 // An explicit new invitation must not reuse a previous decline.
 assert.equal((await f.commit([{...group(f),revision:1}])).status,200);
 assert.ok((await f.state(f.otherToken)).body.meetings.groups[0].pending.includes(f.otherId));
 assert.equal((await f.commit([{kind:'group-answer',id:'group:'+f.otherId,revision:1,value:{groupId:'group',status:'yes'}}],f.otherToken)).status,200);
 assert.ok((await f.state(f.otherToken)).body.meetings.groups[0].members.includes(f.otherId));
 assert.equal((await f.call('/app/state')).status,401);
 f.env.DB.sqlite.prepare('UPDATE members SET active=0 WHERE id=?').run(f.otherId);
 assert.equal((await f.state(f.otherToken)).status,401);
});
